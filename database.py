import os

from sqlalchemy import (
    create_engine,
    text
)

from config import (
    DATABASE_PATH
)


# =========================================================
# DATABASE URL
#
# Docker / cloud:
# Uses DATABASE_URL from the environment.
#
# Local / PyInstaller:
# Falls back to SQLite.
# =========================================================

DATABASE_URL = os.getenv(
    "DATABASE_URL"
)


if DATABASE_URL:

    ACTIVE_DATABASE_URL = (
        DATABASE_URL
    )

    DATABASE_TYPE = (
        "postgresql"
        if DATABASE_URL.startswith(
            "postgresql"
        )
        else "external"
    )

    engine = create_engine(
        ACTIVE_DATABASE_URL,
        pool_pre_ping=True
    )

else:

    ACTIVE_DATABASE_URL = (
        f"sqlite:///{DATABASE_PATH.as_posix()}"
    )

    DATABASE_TYPE = "sqlite"

    engine = create_engine(
        ACTIVE_DATABASE_URL,
        connect_args={
            "check_same_thread":
                False
        }
    )


# =========================================================
# DATABASE CONNECTION
#
# Kept as a compatibility helper.
# New database functions use SQLAlchemy context managers.
# =========================================================

def get_db_connection():

    return engine.connect()


# =========================================================
# DATABASE INITIALIZATION
# =========================================================

def initialize_database():

    create_table_statement = text(
        """
        CREATE TABLE IF NOT EXISTS datasets (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,
            filename TEXT NOT NULL,
            upload_date TEXT NOT NULL,
            rows INTEGER DEFAULT 0,
            columns_count INTEGER DEFAULT 0,
            missing_values INTEGER DEFAULT 0,
            duplicates INTEGER DEFAULT 0,
            quality_score INTEGER DEFAULT 0,
            memory_usage REAL DEFAULT 0
        )
        """
    )


    sqlite_create_table_statement = text(
        """
        CREATE TABLE IF NOT EXISTS datasets (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            filename TEXT NOT NULL,
            upload_date TEXT NOT NULL,
            rows INTEGER DEFAULT 0,
            columns_count INTEGER DEFAULT 0,
            missing_values INTEGER DEFAULT 0,
            duplicates INTEGER DEFAULT 0,
            quality_score INTEGER DEFAULT 0,
            memory_usage REAL DEFAULT 0
        )
        """
    )


    with engine.begin() as connection:

        if DATABASE_TYPE == "sqlite":

            connection.execute(
                sqlite_create_table_statement
            )

        else:

            connection.execute(
                create_table_statement
            )


# =========================================================
# INSERT DATASET HISTORY
# =========================================================

def insert_dataset(
    filename,
    upload_date,
    rows,
    columns_count,
    missing_values,
    duplicates,
    quality_score,
    memory_usage
):

    statement = text(
        """
        INSERT INTO datasets (
            filename,
            upload_date,
            rows,
            columns_count,
            missing_values,
            duplicates,
            quality_score,
            memory_usage
        )
        VALUES (
            :filename,
            :upload_date,
            :rows,
            :columns_count,
            :missing_values,
            :duplicates,
            :quality_score,
            :memory_usage
        )
        """
    )


    values = {
        "filename":
            filename,

        "upload_date":
            upload_date,

        "rows":
            rows,

        "columns_count":
            columns_count,

        "missing_values":
            missing_values,

        "duplicates":
            duplicates,

        "quality_score":
            quality_score,

        "memory_usage":
            memory_usage
    }


    with engine.begin() as connection:

        connection.execute(
            statement,
            values
        )


# =========================================================
# GET DATASET HISTORY
# =========================================================

def get_dataset_history():

    statement = text(
        """
        SELECT
            id,
            filename,
            upload_date,
            rows,
            columns_count,
            missing_values,
            duplicates,
            quality_score,
            memory_usage
        FROM datasets
        ORDER BY id DESC
        """
    )


    with engine.connect() as connection:

        result = connection.execute(
            statement
        )

        return [
            tuple(row)
            for row in result.fetchall()
        ]


