# =========================================================
# ANALYTICS METRICS
# =========================================================

def get_analytics_metrics():

    statement = text(
        """
        SELECT
            COUNT(*) AS total_datasets,
            COALESCE(
                AVG(quality_score),
                0
            ) AS avg_quality,
            COALESCE(
                SUM(rows),
                0
            ) AS total_rows,
            COALESCE(
                SUM(memory_usage),
                0
            ) AS total_memory
        FROM datasets
        """
    )


    with engine.connect() as connection:

        result = connection.execute(
            statement
        )

        row = result.mappings().one()


    return {
        "total_datasets":
            int(
                row[
                    "total_datasets"
                ]
                or 0
            ),

        "avg_quality":
            float(
                row[
                    "avg_quality"
                ]
                or 0
            ),

        "total_rows":
            int(
                row[
                    "total_rows"
                ]
                or 0
            ),

        "total_memory":
            float(
                row[
                    "total_memory"
                ]
                or 0
            )
    }


# =========================================================
# DATABASE HEALTH
# =========================================================

def check_database_connection():

    try:

        with engine.connect() as connection:

            connection.execute(
                text(
                    "SELECT 1"
                )
            )

        return True

    except Exception:

        return False


